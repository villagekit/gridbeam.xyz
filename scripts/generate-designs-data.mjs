#!/usr/bin/env node
// scripts/generate-designs-data.mjs
//
// Reads every product under `./products/<id>/` and emits a single TypeScript
// module (`app/_lib/designs-data.generated.ts`) with the parsed TOML meta + the
// raw text of each design's exported `.ts` file inlined.
//
// We do this because the runtime target (Cloudflare Workers via OpenNext) does
// not bundle arbitrary repo files alongside the worker — only JS that the
// worker imports gets included. Reading `./products/` with `node:fs` at request
// time blows up with `no such file or directory, readdir '/bundle/products'`.
// Generating a JS module that imports the data inline sidesteps that entirely.

import { existsSync } from 'node:fs'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { parse as parseToml } from 'smol-toml'

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DESIGNS_DIR = join(REPO_ROOT, 'products')
const OUT_PATH = join(REPO_ROOT, 'app', '_lib', 'designs-data.generated.ts')

async function main() {
  if (!existsSync(DESIGNS_DIR)) {
    throw new Error(`Designs directory not found: ${DESIGNS_DIR}`)
  }

  const entries = await readdir(DESIGNS_DIR, { withFileTypes: true })
  const ids = entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()

  const designs = await Promise.all(
    ids.map(async (id) => {
      const tomlPath = join(DESIGNS_DIR, id, 'villagekit.toml')
      const tomlContents = await readFile(tomlPath, 'utf8')
      const parsed = parseToml(tomlContents)
      const meta = parsed.product
      if (meta == null || typeof meta !== 'object') {
        throw new Error(`Missing [product] table in ${tomlPath}`)
      }
      if (typeof meta.exports !== 'string') {
        throw new Error(`Missing string \`exports\` in ${tomlPath}`)
      }
      const codePath = join(DESIGNS_DIR, id, meta.exports)
      const code = await readFile(codePath, 'utf8')
      return { id, meta, code }
    }),
  )

  const body = designs
    .map(({ id, meta, code }) => {
      return `  ${JSON.stringify(id)}: {\n    meta: ${JSON.stringify(meta, null, 4).replace(/\n/g, '\n    ')},\n    code: ${JSON.stringify(code)},\n  },`
    })
    .join('\n')

  const output = `// @generated by scripts/generate-designs-data.mjs — DO NOT EDIT.
// Run \`pnpm generate:designs\` after changing files under \`./products/\`.

import type { ProductMeta } from '@villagekit/product'

export interface RawDesignEntry {
  meta: ProductMeta
  code: string
}

export const designsData: Record<string, RawDesignEntry> = {
${body}
}
`

  await writeFile(OUT_PATH, output, 'utf8')
  console.info(`Wrote ${designs.length} designs to ${OUT_PATH.replace(`${REPO_ROOT}/`, '')}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
